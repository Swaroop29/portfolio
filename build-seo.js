// Generates the crawler-friendly outputs from data.js and index.html:
//   - the plain-text version inside index.html (between the TEXT-VERSION markers)
//   - llms.txt, robots.txt, sitemap.xml
// Run with: node build-seo.js   (tests/seo.test.js fails if these are out of date)
const fs = require('fs');
const { JSDOM } = require('jsdom');

const SITE = 'https://swaroop-patil.pages.dev';
const { projects, repos, skills } = new Function(fs.readFileSync('data.js', 'utf8') + '\nreturn {projects,repos,skills}')();
const dec = s => String(s || '').replace(/&middot;/g, '·').replace(/&rarr;/g, '->').replace(/&amp;/g, '&').replace(/&#9733;/g, '*');
const esc = s => String(s || '').replace(/&(?!(middot|rarr|amp|#9733);)/g, '&amp;');

function projectHtml(p) {
  const links = [p.live && ['Live demo', p.live], p.src && ['Source code', p.src], p.blog && ['Write-up', p.blog]].filter(Boolean)
    .map(([n, u]) => '<a href="' + u + '">' + n + '</a>').join(' &middot; ');
  return '<article><h4>' + esc(p.t) + '</h4><p><em>' + esc(p.sub) + ' &middot; ' + esc(p.badge) + '</em></p>' +
    (p.problem ? '<p><b>Problem:</b> ' + esc(p.problem) + '</p>' : '') +
    '<p><b>What I built:</b> ' + esc(p.built) + '</p>' +
    '<p><b>Result:</b> ' + esc(p.result) + '</p><p><b>Built with:</b> ' + esc(p.stack) + '</p><p><b>My role:</b> ' + esc(p.role) + '</p>' +
    (p.arch && p.arch.length ? '<p><b>Architecture:</b> ' + p.arch.map(esc).join(' &rarr; ') + '</p>' : '') +
    (p.diff ? '<p><b>What I would do differently:</b> ' + esc(p.diff) + '</p>' : '') +
    (links ? '<p>' + links + '</p>' : '') + '</article>';
}

const textVersion = '<!-- TEXT-VERSION:START (generated by build-seo.js, do not edit by hand) -->\n' +
  '<details class="textver" id="text-version"><summary>Plain-text version of this portfolio (projects, repositories, skills)</summary>\n' +
  '<h3>Projects</h3>\n' + projects.map(projectHtml).join('\n') + '\n' +
  '<h3>GitHub repositories</h3><ul>' + repos.map(r => '<li><a href="' + r.u + '">' + esc(r.n) + '</a> (' + esc(r.l) + '): ' + esc(r.d) + '</li>').join('') + '</ul>\n' +
  '<h3>Skills</h3><ul>' + skills.map(s => '<li>' + esc(s.n) + ' (' + esc(s.s) + ')</li>').join('') + '</ul>\n' +
  '</details>\n<!-- TEXT-VERSION:END -->';

let html = fs.readFileSync('index.html', 'utf8');
if (html.includes('<!-- TEXT-VERSION:START')) {
  html = html.replace(/<!-- TEXT-VERSION:START[\s\S]*?<!-- TEXT-VERSION:END -->/, () => textVersion);
} else {
  html = html.replace(/(<footer class="pad">[\s\S]*?<\/footer>)/, m => m + '\n' + textVersion);
}
fs.writeFileSync('index.html', html);

// llms.txt: everything, as markdown, from the page itself plus data.js
const doc = new JSDOM(html).window.document;
const flat = e => dec(e.innerHTML.replace(/<\/(p|div|h\d|li|b|span|small)>/g, '$& ').replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ').trim());
const txt = sel => { const e = doc.querySelector(sel); return e ? flat(e) : ''; };
const contact = [...doc.querySelectorAll('#contact a[href]')]
  .map(a => '- ' + a.textContent.trim() + ': ' + a.getAttribute('href').replace(/^mailto:/, '').replace(/^tel:/, '')).join('\n');

const md = '# Swaroop Patil\n\n> Software engineer (backend, distributed systems, cloud, AI tooling). Portfolio: ' + SITE + '\n\n' +
  'This file holds the full content of the portfolio so that people and AI agents can read all of it without running JavaScript.\n\n' +
  '## Contact\n' + contact + '\n\n' +
  '## About\n' + txt('#about .about > div:first-child') + '\n\n' +
  '## Experience\n' + [...doc.querySelectorAll('#episodes .ep-head, #episodes .ep')].map(e => (e.classList.contains('ep-head') ? '\n### ' : '- ') + flat(e)).join('\n') + '\n\n' +
  '## Education\n' + [...doc.querySelectorAll('#edu .stop')].map(e => '- ' + flat(e)).join('\n') + '\n\n' +
  '## Projects\n' + projects.map(p => '### ' + dec(p.t) + '\n' + dec(p.sub) + ' | ' + dec(p.badge) + '\n' +
    (p.problem ? 'Problem: ' + dec(p.problem) + '\n' : '') + 'What I built: ' + dec(p.built) + '\nResult: ' + dec(p.result) + '\nBuilt with: ' + dec(p.stack) + '\nMy role: ' + dec(p.role) + '\n' +
    (p.arch && p.arch.length ? 'Architecture: ' + p.arch.map(dec).join(' -> ') + '\n' : '') + (p.diff ? 'What I would do differently: ' + dec(p.diff) + '\n' : '') +
    [p.live && 'Live demo: ' + p.live, p.src && 'Source: ' + p.src, p.blog && 'Write-up: ' + p.blog].filter(Boolean).join('\n')).join('\n\n') + '\n\n' +
  '## GitHub repositories\n' + repos.map(r => '- ' + r.n + ' (' + r.l + '): ' + dec(r.d) + ' ' + r.u).join('\n') + '\n\n' +
  '## Skills\n' + skills.map(s => '- ' + dec(s.n) + ' (' + dec(s.s) + ')').join('\n') + '\n';
fs.writeFileSync('llms.txt', md);

fs.writeFileSync('robots.txt', 'User-agent: *\nAllow: /\n\nSitemap: ' + SITE + '/sitemap.xml\n');
fs.writeFileSync('sitemap.xml', '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url><loc>' + SITE + '/</loc></url>\n  <url><loc>' + SITE + '/llms.txt</loc></url>\n</urlset>\n');
console.log('built: index.html text version, llms.txt, robots.txt, sitemap.xml');
